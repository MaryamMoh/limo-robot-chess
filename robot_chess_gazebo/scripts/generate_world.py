#!/usr/bin/env python3
"""Generate the Gazebo test world from the player configuration.

    generate_world.py [--config player_sim.yaml] [--world OUT.world]

My robot stands at the world origin, so the board pose given in the
robot's base_footprint frame (config "board") is also its world pose.  The
world contains:
  * a low table whose top overhangs the LIMO's front bumper (legs outside
    the robot's footprint) carrying the board;
  * the 8x8 board, a pad for my captured pieces (graveyard) and an area
    behind rank 8 / rank 1 where the opponent puts the pieces it captures.
The pieces themselves are spawned at runtime by sim_piece_manager.py.
"""
import argparse
import math
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "robot_chess_game", "src"))

from robot_chess.board_geometry import BoardGeometry  # noqa: E402

LIGHT = (0.80, 0.68, 0.48)
DARK = (0.42, 0.28, 0.17)
FRAME = (0.25, 0.16, 0.10)
TABLE = (0.75, 0.75, 0.72)
PAD = (0.55, 0.58, 0.62)
TABLE_THICKNESS = 0.012


def material(rgb):
    r, g, b = rgb
    return ("<material><ambient>{0} {1} {2} 1</ambient><diffuse>{0} {1} {2} 1</diffuse>"
            "<specular>0.05 0.05 0.05 1</specular></material>").format(r, g, b)


def box(name, x, y, z, sx, sy, sz, rgb, collision=False):
    geom = "<geometry><box><size>%.4f %.4f %.4f</size></box></geometry>" % (sx, sy, sz)
    pose = "<pose>%.4f %.4f %.4f 0 0 0</pose>" % (x, y, z)
    out = "<visual name='%s'>%s%s%s</visual>" % (name, pose, geom, material(rgb))
    if collision:
        out += "<collision name='%s_c'>%s%s</collision>" % (name, pose, geom)
    return out


def board_model(g):
    """Board + pads, modelled in the board frame (placed with the board pose)."""
    s = g.square_size
    half = 4 * s
    parts = [box("frame", 0, 0, -0.0015, 2 * half + 0.02, 2 * half + 0.02, 0.003, FRAME)]
    for f in range(8):
        for r in range(8):
            light = (f + r) % 2 == 1
            parts.append(box("sq_%d_%d" % (f, r), (f - 3.5) * s, (r - 3.5) * s, -0.0005,
                             s, s, 0.001, LIGHT if light else DARK))
    xs = [g.graveyard_slot_board(i)[0] for i in range(g.graveyard_slots)]
    ys = [g.graveyard_slot_board(i)[1] for i in range(g.graveyard_slots)]
    parts.append(box("graveyard", (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2, -0.0008,
                     max(xs) - min(xs) + 0.018, max(ys) - min(ys) + 0.018, 0.001, PAD))
    return ("<model name='chessboard'><static>true</static>"
            "<pose>%.4f %.4f %.4f 0 0 %.4f</pose><link name='link'>%s</link></model>" % (
                g.board_x, g.board_y, g.board_z, g.board_yaw, "".join(parts)))


def table_model(g):
    """Table under the board: top just below the board surface, extending
    towards the robot over its bumper; legs outside the robot footprint."""
    top_z = g.board_z - 0.003 - TABLE_THICKNESS / 2
    x0, x1 = 0.06, g.board_x + 4 * g.square_size + 0.12
    y_half = 0.22
    parts = [box("top", (x0 + x1) / 2, 0, top_z, x1 - x0, 2 * y_half, TABLE_THICKNESS,
                 TABLE, collision=True)]
    leg_h = top_z - TABLE_THICKNESS / 2
    for i, (lx, ly) in enumerate([(x0 + 0.02, y_half - 0.02), (x0 + 0.02, -y_half + 0.02),
                                  (x1 - 0.02, y_half - 0.02), (x1 - 0.02, -y_half + 0.02)]):
        parts.append(box("leg%d" % i, lx, ly, leg_h / 2, 0.025, 0.025, leg_h, TABLE,
                         collision=True))
    return ("<model name='table'><static>true</static><link name='link'>%s</link></model>"
            % "".join(parts))


def world_sdf(g):
    return """<?xml version="1.0"?>
<!-- Generated by robot_chess_gazebo/scripts/generate_world.py - do not edit. -->
<sdf version="1.6">
  <world name="chess_table">
    <include><uri>model://sun</uri></include>
    <include><uri>model://ground_plane</uri></include>
    <scene>
      <ambient>0.7 0.7 0.7 1</ambient>
      <background>0.75 0.8 0.85 1</background>
      <shadows>false</shadows>
    </scene>
    <physics type="ode">
      <max_step_size>0.002</max_step_size>
      <real_time_factor>1</real_time_factor>
      <real_time_update_rate>500</real_time_update_rate>
    </physics>
    <gui>
      <camera name="user_camera">
        <pose>-0.45 -0.55 0.75 0 0.6 0.75</pose>
      </camera>
    </gui>
    %s
    %s
  </world>
</sdf>
""" % (table_model(g), board_model(g))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--config", default=os.path.join(
        REPO, "robot_chess_game", "config", "player_sim.yaml"))
    ap.add_argument("--world", default=os.path.join(
        REPO, "robot_chess_gazebo", "worlds", "chess_table.world"))
    args = ap.parse_args()
    with open(args.config) as f:
        g = BoardGeometry.from_dict(yaml.safe_load(f)["board"])
    os.makedirs(os.path.dirname(os.path.abspath(args.world)), exist_ok=True)
    with open(args.world, "w", newline="\n") as f:
        f.write(world_sdf(g))
    print("wrote %s" % args.world)


if __name__ == "__main__":
    main()
